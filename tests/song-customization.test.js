const { test }=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createApplication}=require('../src/app');
test('biblioteca exige tres confirmaciones; estilos y archivos sobreviven y la previsualización no proyecta',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'song-customization-'));
 const song={id:'001',number:1,title:'Canto de prueba',sections:[{type:'verse',label:'Estrofa 1',lines:['Cantamos juntos con alegría al Señor porque su amor permanece para siempre.']},{type:'chorus',label:'Coro',lines:['Alabemos su nombre con gratitud.']}]};
 for(const name of ['himnario_lldm.json','coro_lldm.json'])fs.writeFileSync(path.join(dir,name),JSON.stringify([song]));
 let app,base;
 async function start(){app=createApplication({dataDir:dir,uploadsDir:path.join(dir,'uploads'),obs:false,watchFiles:false});await new Promise(r=>app.server.listen(0,'127.0.0.1',r));base=`http://127.0.0.1:${app.server.address().port}`;}
 t.after(async()=>{await app?.close();fs.rmSync(dir,{recursive:true,force:true});});await start();
 const get=async url=>(await fetch(base+url)).json();
 const send=(url,body,method='POST')=>fetch(base+url,{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
 let snapshot=await get('/api/settings');
 const fontData=new FormData();fontData.append('file',new Blob([fs.readFileSync(path.join(__dirname,'../public/fonts/Playfair-Display.woff2'))]),'elegante.woff2');
 const fontResponse=await fetch(base+'/api/song-assets/font',{method:'POST',body:fontData});assert.equal(fontResponse.status,200);const font=await fontResponse.json();
 assert.equal((await fetch(base+font.url)).status,200);
 const imageData=new FormData();imageData.append('file',new Blob([fs.readFileSync(path.join(__dirname,'../docs/capturas/02-himnario-acciones.png'))]),'fondo.png');
 const imageResponse=await fetch(base+'/api/song-assets/image',{method:'POST',body:imageData});assert.equal(imageResponse.status,200);const background=await imageResponse.json();
 const settings=structuredClone(snapshot.settings);settings.lyrics.hymn={...settings.lyrics.hymn,maxLines:3,minFontSize:120,fontSize:180,font:font.id,color:'#ffeebb',chorusColor:'#ffcc44',showVerseNumber:true,background:background.id};
 const before=await get('/api/state');
 const previewResponse=await send('/api/lyrics/preview',{type:'hymn',id:'001',lyrics:settings.lyrics});
 const preview=await previewResponse.json();assert.equal(previewResponse.status,200,JSON.stringify(preview));
 assert.ok(preview.slides.filter(s=>!s.isTitleOnly).every(s=>s.displayLines.length<=3));
 assert.deepEqual(await get('/api/state'),before);
 assert.equal((await send('/api/settings',{revision:snapshot.revision,settings},'PUT')).status,200);
 await send('/api/project/hymn',{hymnId:'001'});
 assert.equal((await get('/api/state')).displayPayload.appearance.backgroundUrl,background.url);
 const bad=structuredClone(settings);bad.lyrics.hymn.maxLines=0;assert.equal((await send('/api/settings',{revision:1,settings:bad},'PUT')).status,400);
 const corrupt=new FormData();corrupt.append('file',new Blob(['not a font']),'bad.ttf');assert.equal((await fetch(base+'/api/song-assets/font',{method:'POST',body:corrupt})).status,400);
 const added=await send('/api/library/himnos',{...song,number:2});assert.equal(added.status,201);const created=(await added.json()).song;
 const addedChoir=await(await send('/api/library/coro',{...song,number:null})).json();
 assert.equal((await send('/api/project/choir',{choirId:'001'})).status,200);
 assert.equal((await send('/api/songs/coro/'+addedChoir.song.id+'/save',{title:'Nombre corregido',sections:song.sections,updateActiveProjection:true})).status,200);
 assert.equal((await get('/api/state')).activeItem.id,'001','editar otro canto sin número no reemplaza el canto activo');
 assert.equal((await get('/api/coro?q=nombre%20corregido'))[0].id,addedChoir.song.id);
 assert.equal((await send('/api/library/himnos',{...song,number:2})).status,409);
 const url='/api/library/himnos/'+created.id;
 assert.equal((await send(url,{},'DELETE')).status,409);
 const first=await(await send(url+'/delete-check',{step:1})).json();
 assert.equal((await send(url,{token:first.token,confirmation:created.title},'DELETE')).status,409);
 assert.equal((await send(url+'/delete-check',{step:2,token:first.token})).status,200);
 assert.equal((await send(url,{token:first.token,confirmation:'otro título'},'DELETE')).status,409);
 assert.equal((await send(url,{token:first.token,confirmation:created.title},'DELETE')).status,200);
 assert.equal((await get('/api/himnos')).length,1);
 await app.close();await start();
 assert.deepEqual((await get('/api/settings')).settings,settings);assert.ok((await get('/api/song-assets')).some(asset=>asset.id===font.id));
 assert.equal((await get('/api/himnos')).length,1);
});
